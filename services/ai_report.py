"""
ai_report.py: Grounded, non-diagnostic AI patient report generator.
Supports OpenAI (primary) and Google Gemini via configurable environment variables,
with a robust 12-section deterministic clinical template fallback when API keys are unconfigured.

SAFETY & COMPLIANCE RULES:
1. NEVER diagnose a patient.
2. NEVER prescribe medications or suggest dosages.
3. NEVER claim clinical certainty or replace qualified physician consultation.
4. Base all statements strictly on entered measurements, predicted probability, and SHAP/LIME factors.
5. Always display prominent non-diagnostic research/educational disclaimers.
"""

import json
import os
from pathlib import Path
from typing import Any, Dict, List, Optional
import requests

from services.recommendations import generate_personalized_recommendations

try:
    from dotenv import load_dotenv
    load_dotenv()
except Exception:
    env_file = Path(".env")
    if env_file.exists():
        try:
            with open(env_file, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith("#") and "=" in line:
                        k, v = line.split("=", 1)
                        k, v = k.strip(), v.strip().strip("'\"")
                        if k and k not in os.environ:
                            os.environ[k] = v
        except Exception:
            pass

MANDATORY_DISCLAIMER = (
    "This report is generated by an AI-based research prototype for educational purposes. "
    "It is not a medical diagnosis and should not replace consultation with a qualified healthcare professional."
)


def get_llm_status() -> Dict[str, Any]:
    """
    Returns the current LLM configuration state without exposing the API key.
    """
    provider = os.getenv("LLM_PROVIDER", "openai").strip().lower()
    default_model = "gpt-4o-mini" if provider == "openai" else "gemini-1.5-flash"
    model = os.getenv("LLM_MODEL", default_model).strip()
    api_key = os.getenv("LLM_API_KEY", "").strip()

    is_configured = bool(api_key)
    return {
        "is_configured": is_configured,
        "provider": provider,
        "model": model,
        "has_key": is_configured,
    }


def _build_12_section_text(
    patient_data: Dict[str, Any],
    prediction: int,
    probability: float,
    top_shap_features: List[Dict[str, Any]],
    lime_features: Optional[List[Dict[str, Any]]],
    model_info: Dict[str, Any],
    interpretation_text: str,
    recommendations: List[str],
) -> str:
    """Builds the complete, standardized 12-section clinical assessment report text."""
    risk_label = "Higher Risk (Class 1)" if prediction == 1 else "Lower Risk (Class 0)"
    prob_pct = f"{probability * 100:.2f}%"
    model_name = model_info.get("model_name", "XGBoost (Baseline)")
    roc_auc = model_info.get("roc_auc", 0.8198)

    # 1. Title & Header
    lines = [
        "================================================================================",
        "                     DIABETES RISK ASSESSMENT REPORT",
        "================================================================================",
        "",
        "1. DIABETES RISK ASSESSMENT",
        "--------------------------------------------------------------------------------",
        f"Computational screening indicates a classification of: {risk_label}.",
        "This assessment reflects learned statistical patterns from the training cohort",
        "and is intended solely for research, screening, and educational decision support.",
        "",
        "2. PREDICTION SUMMARY",
        "--------------------------------------------------------------------------------",
        f"Categorical Classification : {risk_label}",
        "Decision Boundary (tau)    : 50.00% (Standard Diagnostic Cutoff)",
        f"Categorical Outcome        : {'Elevated Likelihood' if prediction == 1 else 'Low / Moderate Baseline Likelihood'}",
        "",
        "3. ESTIMATED PROBABILITY",
        "--------------------------------------------------------------------------------",
        f"Predicted Diabetes Risk    : {prob_pct}",
        f"Distance from Threshold    : {abs(probability - 0.5) * 100:.2f} percentage points",
        "",
        "4. PATIENT INPUT SUMMARY & DEMOGRAPHIC PROFILE",
        "--------------------------------------------------------------------------------",
        f"- Patient Name             : {patient_data.get('Name', 'Anonymous Patient')}",
        f"- Biological Sex           : {patient_data.get('Sex', patient_data.get('Gender', 'Female'))}",
        f"- Age                      : {patient_data.get('Age', 'N/A')} years",
        f"- Pregnancies              : {patient_data.get('Pregnancies', 0)}",
        f"- Glucose                  : {patient_data.get('Glucose', 'N/A')} mg/dL",
        f"- Blood Pressure           : {patient_data.get('BloodPressure', 'N/A')} mmHg",
        f"- Skin Thickness           : {patient_data.get('SkinThickness', 'N/A')} mm",
        f"- Insulin                  : {patient_data.get('Insulin', 'N/A')} muU/mL",
        f"- Body Mass Index (BMI)    : {patient_data.get('BMI', 'N/A')} kg/m²",
        f"- Diabetes Pedigree Funct. : {patient_data.get('DiabetesPedigreeFunction', 'N/A')}",
        "",
        "5. KEY FACTORS INFLUENCING THE MODEL",
        "--------------------------------------------------------------------------------",
    ]

    for idx, f in enumerate(top_shap_features[:5], start=1):
        feat = f.get("Feature", "Unknown")
        val = f.get("Patient_Value", patient_data.get(feat, "N/A"))
        direction = f.get("Direction", "Influences prediction")
        lines.append(f"  {idx}. {feat:<24} = {str(val):<6} ({direction})")

    lines.extend(
        [
            "",
            "6. SHAP EXPLANATION",
            "--------------------------------------------------------------------------------",
            "SHAP (SHapley Additive exPlanations) attributes a signed numerical shift to each",
            "feature relative to the expected log-odds of diabetes across the cohort:",
        ]
    )
    for idx, f in enumerate(top_shap_features[:5], start=1):
        feat = f.get("Feature", "Unknown")
        shap_val = f.get("SHAP_Value", 0.0)
        direction = f.get("Direction", "neutral")
        lines.append(f"  - {feat:<24} : SHAP {shap_val:+.4f} | {direction}")

    lines.extend(
        [
            "",
            "7. LIME EXPLANATION",
            "--------------------------------------------------------------------------------",
            "LIME constructs a local linear surrogate model around this specific patient:",
        ]
    )
    if lime_features:
        for idx, lf in enumerate(lime_features[:5], start=1):
            cond = lf.get("Condition", lf.get("Feature", "Feature"))
            weight = lf.get("LIME_Weight", 0.0)
            lines.append(f"  - Condition: {cond:<35} | Weight: {weight:+.4f}")
    else:
        lines.append("  - LIME surrogate weights align with top SHAP feature rankings.")

    lines.extend(
        [
            "",
            "8. MODEL INFORMATION",
            "--------------------------------------------------------------------------------",
            f"Algorithm Evaluated        : {model_name}",
            f"Holdout ROC-AUC Score      : {roc_auc:.4f}",
            "Cross-Validation Scheme    : 5-Fold Stratified Cross-Validation",
            "Validation Cohort          : PIMA Indians Diabetes Database (N=768)",
            "",
            "9. INTERPRETATION OF THE PREDICTION",
            "--------------------------------------------------------------------------------",
            interpretation_text.strip(),
            "",
            "10. GENERAL EDUCATIONAL INFORMATION",
            "--------------------------------------------------------------------------------",
        ]
    )
    for rec in recommendations:
        lines.append(f"• {rec}")

    lines.extend(
        [
            "",
            "11. LIMITATIONS",
            "--------------------------------------------------------------------------------",
            "- Demographic Scope: Model was trained on female Pima Indian patients aged >= 21.",
            "- Imputation Variance: Implausible zero measurements in Glucose, BP, Skin Thickness,",
            "  Insulin, and BMI are imputed with cohort medians, which may introduce variance.",
            "- Non-Causality: Feature attributions indicate statistical reliance within the",
            "  algorithm, NOT clinical biological causality.",
            "",
            "12. MEDICAL DISCLAIMER",
            "--------------------------------------------------------------------------------",
            MANDATORY_DISCLAIMER,
            "================================================================================",
        ]
    )

    return "\n".join(lines)


def _build_rule_based_interpretation(
    patient_data: Dict[str, Any],
    prediction: int,
    probability: float,
    top_shap_features: List[Dict[str, Any]],
    model_name: str,
) -> str:
    """Constructs a deterministic, evidence-grounded natural language explanation."""
    risk_str = "higher risk" if prediction == 1 else "lower risk"
    prob_pct = f"{probability * 100:.1f}%"

    drivers_inc = [f["Feature"] for f in top_shap_features if "higher" in f.get("Direction", "").lower()]
    drivers_dec = [f["Feature"] for f in top_shap_features if "lower" in f.get("Direction", "").lower()]

    parts = [
        f"The {model_name} evaluated this patient profile with an estimated probability of {prob_pct}, "
        f"classifying the profile into the {risk_str} tier relative to the default 50% decision boundary."
    ]

    if drivers_inc:
        feat_list = ", ".join(drivers_inc[:3])
        parts.append(
            f"According to the model explanation, the variables most strongly pushing the prediction "
            f"toward higher risk were {feat_list}."
        )

    if drivers_dec:
        feat_list = ", ".join(drivers_dec[:2])
        parts.append(
            f"Conversely, {feat_list} acted as mitigating or stabilizing factors in the model's decision logic."
        )

    parts.append(
        "These explanations describe the mathematical attributions learned by the machine learning algorithm "
        "and should be interpreted as computational insights rather than direct medical causation."
    )

    return " ".join(parts)


def _build_educational_recommendations(probability: float) -> List[str]:
    """Generates general, non-prescriptive lifestyle and monitoring guidelines."""
    recommendations = [
        "Schedule regular wellness screenings and review fasting blood glucose tests with a physician.",
        "Maintain a nutrient-dense diet emphasizing complex dietary fiber, whole grains, and lean proteins.",
        "Engage in consistent physical activity (aiming for at least 150 minutes of moderate exercise weekly).",
        "Routinely monitor blood pressure and cardiovascular wellness markers.",
    ]
    if probability >= 0.5:
        recommendations.append(
            "Given the elevated computational risk score, discuss confirmatory diagnostic laboratory testing (such as HbA1c) with a licensed healthcare provider."
        )
    return recommendations


def generate_fallback_report(
    patient_data: Dict[str, Any],
    prediction: int,
    probability: float,
    top_shap_features: List[Dict[str, Any]],
    model_info: Optional[Any] = None,
    lime_features: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Generates a complete 12-section clinical report using the deterministic fallback engine.
    Ensures 100% availability when LLM API keys are unconfigured or unavailable.
    """
    if isinstance(model_info, list) and lime_features is None:
        # Handled in case lime_features was passed as 5th positional arg
        lime_features = model_info
        model_info = None
    if not isinstance(model_info, dict):
        model_info = {"model_name": "XGBoost (Baseline)", "roc_auc": 0.8198}

    model_name = model_info.get("model_name", "XGBoost (Baseline)")
    interpretation = _build_rule_based_interpretation(
        patient_data, prediction, probability, top_shap_features, model_name
    )
    personalized_guidance = generate_personalized_recommendations(
        patient_data=patient_data,
        shap_features=top_shap_features,
        prediction_probability=probability,
    )
    recommendations = []
    for area in personalized_guidance.get("priority_areas", []):
        recommendations.append(f"[{area['display_name']}] {area['guidance'][0]}")
    for w in personalized_guidance.get("general_wellness", []):
        recommendations.append(w)

    report_text = _build_12_section_text(
        patient_data=patient_data,
        prediction=prediction,
        probability=probability,
        top_shap_features=top_shap_features,
        lime_features=lime_features,
        model_info=model_info,
        interpretation_text=interpretation,
        recommendations=recommendations,
    )

    return {
        "is_ai_generated": False,
        "provider": "Deterministic Template Engine (Fallback)",
        "model": "Rule-Based Fallback",
        "status_message": "AI report generation is currently unavailable (no API key configured). Showing a template-based explanation instead.",
        "report_text": report_text,
        "interpretation": interpretation,
        "recommendations": recommendations,
        "personalized_guidance": personalized_guidance,
        "disclaimer": MANDATORY_DISCLAIMER,
    }


def generate_patient_report(
    patient_data: Dict[str, Any],
    prediction: int,
    probability: float,
    shap_results: List[Dict[str, Any]],
    model_info: Optional[Any] = None,
    lime_results: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Generates a professional 12-section Diabetes Risk Assessment Report.
    Queries the configured LLM (OpenAI or Gemini) if an API key is provided in .env.
    If the API key is missing or the call fails, gracefully falls back to the deterministic
    rule-based template without crashing.
    """
    if isinstance(model_info, list) and lime_results is None:
        lime_results = model_info
        model_info = None
    if not isinstance(model_info, dict):
        model_info = {"model_name": "XGBoost (Baseline)", "roc_auc": 0.8198}

    api_key = os.getenv("LLM_API_KEY", "").strip()
    provider = os.getenv("LLM_PROVIDER", "openai").strip().lower()
    default_model = "gpt-4o-mini" if provider == "openai" else "gemini-1.5-flash"
    model = os.getenv("LLM_MODEL", default_model).strip()

    # If no API key configured, use deterministic template
    if not api_key:
        return generate_fallback_report(
            patient_data=patient_data,
            prediction=prediction,
            probability=probability,
            top_shap_features=shap_results,
            model_info=model_info,
            lime_features=lime_results,
        )

    # Compute personalized recommendations
    personalized_guidance = generate_personalized_recommendations(
        patient_data=patient_data,
        shap_features=shap_results,
        prediction_probability=probability,
    )

    # Format grounded context for the prompt
    top_shap_summary = [
        f"{f.get('Feature')}: {f.get('Patient_Value')} (SHAP: {f.get('SHAP_Value', 0.0):+.4f}, {f.get('Direction')})"
        for f in shap_results[:5]
    ]
    lime_summary = (
        [f"{f.get('Condition')}: weight {f.get('LIME_Weight', 0.0):+.4f}" for f in lime_results[:5]]
        if lime_results
        else ["Aligned with top SHAP rankings"]
    )

    prompt = f"""You are a clinical decision-support AI assistant explaining a machine learning diabetes prediction.

CRITICAL INSTRUCTIONS & ETHICAL GUARDRAILS:
1. Base your explanation ONLY on the provided patient data and model attributions below.
2. DO NOT invent symptoms, medical history, medications, lab tests, diagnoses, or demographic info.
3. DO NOT diagnose the patient or claim certainty.
4. DO NOT prescribe medications or recommend dosages.
5. Explain the MACHINE LEARNING MODEL'S behavior. Use language such as:
   - "The model estimated..."
   - "The model was influenced by..."
   - "According to the model explanation..."
   Do NOT say "You definitely have diabetes" or "You should take medication X".

GROUND TRUTH CONTEXT:
- Patient Demographics: Name: {patient_data.get('Name', 'Anonymous Patient')}, Sex: {patient_data.get('Sex', patient_data.get('Gender', 'Female'))}, Age: {patient_data.get('Age', 'N/A')} years
- Patient Clinical Measurements: {patient_data}
- Model Name: {model_info.get('model_name', 'XGBoost')}
- Model Holdout ROC-AUC: {model_info.get('roc_auc', 0.8198):.4f}
- Classification: {'Higher Risk (Class 1)' if prediction == 1 else 'Lower Risk (Class 0)'}
- Estimated Probability: {probability * 100:.2f}% (Threshold: 50%)
- Top 5 SHAP Attributions: {top_shap_summary}
- Primary Upward Contributors: {personalized_guidance['top_upward_features']}
- Model-Based Summary: {personalized_guidance['summary_text']}
- LIME Surrogate Rules: {lime_summary}

TASK:
Write a clear, non-technical 2-paragraph narrative interpretation of what the model considered important for this specific patient:
Paragraph 1: Explain the primary clinical factors that pushed the model toward higher or lower risk according to SHAP and LIME.
Paragraph 2: Provide general, healthy lifestyle guidelines for blood sugar awareness, and recommend reviewing findings with a qualified physician.
"""

    try:
        # Option 1: OpenAI (Primary)
        if provider == "openai":
            url = "https://api.openai.com/v1/chat/completions"
            headers = {
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json",
            }
            payload = {
                "model": model or "gpt-4o-mini",
                "messages": [
                    {
                        "role": "system",
                        "content": "You are a professional Explainable AI clinical assistant. Always ground explanations strictly in provided ML attributions without diagnosing.",
                    },
                    {"role": "user", "content": prompt},
                ],
                "temperature": 0.2,
                "max_tokens": 500,
            }
            resp = requests.post(url, json=payload, headers=headers, timeout=15)
            if resp.status_code == 200:
                data = resp.json()
                ai_interpretation = data["choices"][0]["message"]["content"].strip()

                recommendations = []
                for area in personalized_guidance.get("priority_areas", []):
                    recommendations.append(f"[{area['display_name']}] {area['guidance'][0]}")
                for w in personalized_guidance.get("general_wellness", []):
                    recommendations.append(w)

                full_text = _build_12_section_text(
                    patient_data=patient_data,
                    prediction=prediction,
                    probability=probability,
                    top_shap_features=shap_results,
                    lime_features=lime_results,
                    model_info=model_info,
                    interpretation_text=ai_interpretation,
                    recommendations=recommendations,
                )

                return {
                    "is_ai_generated": True,
                    "provider": f"OpenAI ({model})",
                    "model": model,
                    "status_message": f"Successfully generated via OpenAI ({model}).",
                    "report_text": full_text,
                    "interpretation": ai_interpretation,
                    "recommendations": recommendations,
                    "personalized_guidance": personalized_guidance,
                    "disclaimer": MANDATORY_DISCLAIMER,
                }
            else:
                err_text = resp.text[:200]
                status_note = f"OpenAI API returned HTTP {resp.status_code}: {err_text}"

        # Option 2: Google Gemini
        elif provider in {"gemini", "google"}:
            requested_model = model or "gemini-flash-lite-latest"
            gemini_candidates = [requested_model, "gemini-flash-lite-latest", "gemini-3.5-flash-lite", "gemini-flash-latest"]
            seen_models = set()
            success_model = None
            ai_interpretation = ""

            for gemini_model in gemini_candidates:
                if not gemini_model or gemini_model in seen_models:
                    continue
                seen_models.add(gemini_model)

                url = f"https://generativelanguage.googleapis.com/v1beta/models/{gemini_model}:generateContent?key={api_key}"
                payload = {
                    "contents": [{"parts": [{"text": prompt}]}],
                    "generationConfig": {"temperature": 0.2, "maxOutputTokens": 500},
                }
                try:
                    resp = requests.post(url, json=payload, timeout=15)
                    if resp.status_code == 200:
                        data = resp.json()
                        candidates = data.get("candidates", [])
                        if candidates:
                            parts = candidates[0].get("content", {}).get("parts", [])
                            text_chunks = [p.get("text", "") for p in parts if p.get("text")]
                            if text_chunks:
                                ai_interpretation = "\n\n".join(text_chunks).strip()
                                success_model = gemini_model
                                break
                    else:
                        err_text = resp.text[:200]
                        status_note = f"Gemini API ({gemini_model}) returned HTTP {resp.status_code}: {err_text}"
                except Exception as ex:
                    status_note = f"Gemini API ({gemini_model}) request failed: {str(ex)[:150]}"

            if success_model and ai_interpretation:
                recommendations = []
                for area in personalized_guidance.get("priority_areas", []):
                    recommendations.append(f"[{area['display_name']}] {area['guidance'][0]}")
                for w in personalized_guidance.get("general_wellness", []):
                    recommendations.append(w)

                full_text = _build_12_section_text(
                    patient_data=patient_data,
                    prediction=prediction,
                    probability=probability,
                    top_shap_features=shap_results,
                    lime_features=lime_results,
                    model_info=model_info,
                    interpretation_text=ai_interpretation,
                    recommendations=recommendations,
                )

                return {
                    "is_ai_generated": True,
                    "provider": f"Google Gemini ({success_model})",
                    "model": success_model,
                    "status_message": f"Successfully generated via Google Gemini ({success_model}).",
                    "report_text": full_text,
                    "interpretation": ai_interpretation,
                    "recommendations": recommendations,
                    "personalized_guidance": personalized_guidance,
                    "disclaimer": MANDATORY_DISCLAIMER,
                }
        else:
            status_note = f"Unsupported LLM provider '{provider}'."

    except Exception as e:
        status_note = f"LLM API request failed ({type(e).__name__}): {str(e)[:150]}"

    # If any error occurred during LLM call, fall back gracefully
    fallback = generate_fallback_report(
        patient_data=patient_data,
        prediction=prediction,
        probability=probability,
        top_shap_features=shap_results,
        model_info=model_info,
        lime_features=lime_results,
    )
    fallback["status_message"] = (
        f"AI report generation unavailable ({status_note}). Showing template-based explanation instead."
    )
    return fallback
